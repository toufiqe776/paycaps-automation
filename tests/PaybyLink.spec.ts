import { test, expect } from '@playwright/test';

test('test', async ({ page }) => {
  await page.goto('https://sandbox.paycaps.com/crm/login');
  await page.getByRole('textbox', { name: 'Email Address' }).click();
  await page.getByRole('textbox', { name: 'Email Address' }).fill('sayed@paycaps.com');
  await page.getByRole('textbox', { name: 'Password' }).click();
  await page.getByRole('textbox', { name: 'Password' }).fill('Paycaps!@#22');
  await page.getByRole('textbox', { name: 'Captcha' }).click();
  await page.getByRole('textbox', { name: 'Captcha' }).press('Tab');
  await page.getByRole('textbox', { name: 'Captcha' }).click();
await page.waitForTimeout(10000);
  await page.getByRole('button', { name: 'Sign In' }).click();
  await page.getByRole('button', { name: 'Pay By Link' }).click();
  await page.getByRole('button', { name: 'Create' }).click();
  await page.getByRole('combobox', { name: 'Merchant' }).click();
  await page.getByRole('combobox', { name: 'Merchant' }).fill('super');
  await page.getByRole('option', { name: 'Super Merchant (supermerchant' }).click();
  await page.getByRole('textbox', { name: 'Amount' }).click();
  await page.getByRole('textbox', { name: 'Amount' }).fill('10.00');
  await page.getByRole('textbox', { name: 'Customer Email' }).click();
  await page.getByRole('textbox', { name: 'Customer Email' }).fill('test@yopmail.com');
  await page.getByRole('textbox', { name: 'Customer Email' }).press('Tab');
  await page.getByRole('textbox', { name: 'Customer Name' }).fill('test user');
  await page.getByRole('textbox', { name: 'Phone Number' }).click();
  await page.getByRole('textbox', { name: 'Phone Number' }).fill('501234567');
  await page.getByRole('textbox', { name: 'Purpose (0/100)' }).click();
  await page.getByRole('textbox', { name: 'Purpose (0/100)' }).fill('testing');
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Generate link' }).click();
  const page1Promise = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Open' }).click();
  const page1 = await page1Promise;
  await page1.getByRole('button', { name: 'PAY NOW' }).click();
  await page1.getByRole('textbox', { name: 'XXXX - XXXX - XXXX - XXXX' }).click();
  await page1.getByRole('textbox', { name: 'XXXX - XXXX - XXXX - XXXX' }).fill('4111 1100 0000 0211');
  await page1.getByRole('textbox', { name: 'MM/YY' }).fill('01/34');
  await page1.getByRole('textbox', { name: 'CVV' }).fill('111');
  await page1.getByRole('textbox', { name: 'Name on Card' }).fill('test user');
  await page1.getByRole('button', { name: 'Pay AED' }).click();
  await page1.locator('#otp').click();
  await page1.locator('#otp').fill('111111');
  await page1.getByRole('button', { name: 'Simulate Success' }).click();
  await expect(page1.locator('body')).toContainText('Captured');
  await expect(page1.locator('body')).toContainText('Captured');
});